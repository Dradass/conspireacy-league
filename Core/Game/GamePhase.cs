namespace ConspiracyLeague.Core.Game;

/// <summary>
/// Фаза партии.
/// </summary>
/// <remarks>
/// Подготовка выполняется один раз при старте. Дальше идут раунды: ходы игроков, проверка штабов теорий,
/// доход от адептов, обновление карточек и обновление рынка. Когда при обновлении рынка в колоде не осталось
/// карточек, раунды заканчиваются: идёт итоговый подсчёт денег, и партия завершена.
/// </remarks>
public enum GamePhase
{
  /// <summary>
  /// Подготовка: колода перемешана, игрокам раздаются стартовые карточки, на рынке открываются карточки.
  /// </summary>
  Setup,

  /// <summary>
  /// Ходы игроков — пока все не спасуют.
  /// </summary>
  PlayerTurns,

  /// <summary>
  /// Проверка штабов теорий: несостоятельные закрываются.
  /// </summary>
  HeadquartersCheck,

  /// <summary>
  /// Адепты несут деньги лидерам действующих теорий.
  /// </summary>
  AdeptIncome,

  /// <summary>
  /// Обновление карточек: сыгранные карточки личных штабов переворачиваются лицевой стороной вверх.
  /// </summary>
  CardsRefresh,

  /// <summary>
  /// Обновление рынка.
  /// </summary>
  MarketRefresh,

  /// <summary>
  /// Итоговый подсчёт: владельцы действующих теорий получают деньги за лидеров (<see cref="Field.LeadersBonus"/>).
  /// </summary>
  FinalLeadersBonus,

  /// <summary>
  /// Итоговый подсчёт: адепты действующих теорий ещё раз приносят деньги лидерам.
  /// </summary>
  FinalAdeptIncome,

  /// <summary>
  /// Партия завершена.
  /// </summary>
  GameOver,
}
